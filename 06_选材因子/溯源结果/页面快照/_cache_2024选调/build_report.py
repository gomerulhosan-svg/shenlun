def load(name):
    with open(os.path.join(CACHE, name), encoding="utf-8") as f:
        return f.read()


def grab(name, start, end, inclusive_end=True):
    """从 start 起截到 end 结束（含）。找不到就抛错，避免悄悄截错。"""
    t = load(name)
    i = t.index(start)
    j = t.index(end, i) + (len(end) if inclusive_end else 0)
    return t[i:j]


def quote(text):
    lines = [ln for ln in text.splitlines() if ln.strip() not in ('">', '"', "'")]
    return "\n".join("> " + ln for ln in lines)


