_cache = {}
ERRORS = []


def lines(fn):
    if fn not in _cache:
        p = os.path.join(CACHE, fn)
        _cache[fn] = open(p, encoding="utf-8", errors="ignore").read().split("\n")
    return _cache[fn]


def q(fn, a, b, must=None):
    """取 fn 的第 a..b 行（1 起、含两端）逐字返回；must 里的串必须命中。"""
    L = lines(fn)
    seg = [x.strip() for x in L[a - 1:b] if x.strip()]
    body = "\n".join(seg)
    for m in (must or []):
        if m not in body:
            ERRORS.append("MISS %s:%d-%d 找不到「%s」" % (fn, a, b, m))
    return "\n".join("> " + x for x in seg)


def block(title, degree, sources, anon="无"):
    out = ["### " + title, "- 对应程度：" + degree]
    for i, s in enumerate(sources, 1):
        out.append("- 来源%d：%s｜%s｜%s｜%s｜是否打开了全文：%s" %
                   (i, s["t"], s["m"], s["d"], s["u"], s["o"]))
        for note in s.get("notes", []):
            out.append("  - " + note)
        if s.get("nq"):
            out.append("  - 原文：（这一条只用检索摘要确认了标题与大意，没有用 fetch.py 打开全文；"
                       "按规则不把摘要当原文贴，故此处不贴。）")
        else:
            out.append("  - 原文（逐字粘贴，和这段材料对应的那一整段；前后各多贴一段）：")
            out.append(q(s["f"], s["a"], s["b"], s.get("must")))
    out.append("- 匿名对象识别：" + anon)
    return "\n".join(out)


