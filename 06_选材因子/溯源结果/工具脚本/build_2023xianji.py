def ex(name, start, end, before=0, after=0):
    """从快照 name 里截取 start..end 之间的原文，逐行加 > 前缀。"""
    t = load(name)
    i = t.find(start)
    if i < 0:
        raise SystemExit("起句没找到 in %s: %s" % (name, start[:40]))
    j = t.find(end, i)
    if j < 0:
        raise SystemExit("止句没找到 in %s: %s" % (name, end[:40]))
    seg = t[i:j + len(end)]
    return "\n".join("> " + l for l in seg.split("\n"))


