def lines(name):
    with open(os.path.join(C, name), encoding="utf-8") as f:
        return [l for l in f.read().split("\n") if l.strip()]


def q(name, anchor, before=1, after=1, indent=2):
    """取 anchor 所在段 ±before/after 段，逐字输出为引用块。"""
    ls = lines(name)
    idx = [i for i, l in enumerate(ls) if anchor in l]
    if len(idx) != 1:
        raise SystemExit("锚点不唯一或未命中：%r -> %s" % (anchor, idx))
    i = idx[0]
    a, b = max(0, i - before), min(len(ls), i + after + 1)
    pad = " " * indent
    return "\n".join(pad + "> " + l for l in ls[a:b])


def q_all(name, anchor, before=1, after=1, indent=2):
    """anchor 在报告里可能不止一处命中，全部照抄；相邻的块并成一块，中间用「……」隔开。"""
    ls = lines(name)
    idx = [i for i, l in enumerate(ls) if anchor in l]
    if not idx:
        raise SystemExit("锚点未命中：%r" % anchor)
    spans, pad = [], " " * indent
    for i in idx:
        a, b = max(0, i - before), min(len(ls), i + after + 1)
        if spans and a <= spans[-1][1]:
            spans[-1][1] = max(spans[-1][1], b)
        else:
            spans.append([a, b])
    out = []
    for a, b in spans:
        if out:
            out.append(pad + "> ……")
        out += [pad + "> " + l for l in ls[a:b]]
    return "\n".join(out)


def qrange(name, start, end, indent=2):
    ls = lines(name)
    i = next(k for k, l in enumerate(ls) if l.startswith(start))
    j = next(k for k, l in enumerate(ls) if l.startswith(end)) + 1
    pad = " " * indent
    return "\n".join(pad + "> " + l for l in ls[i:j])


