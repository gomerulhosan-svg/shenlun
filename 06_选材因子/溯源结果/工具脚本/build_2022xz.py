def longest_common(seg, doc):
    """去空白后逐字比，返回 (最长连续重合的长度, 那一串)。"""
    sm = difflib.SequenceMatcher(None, doc, seg, autojunk=False)
    bl = sm.get_matching_blocks()
    if not bl:
        return 0, ""
    b = max(bl, key=lambda x: x.size)
    return b.size, seg[b.b:b.b + b.size]


