    """从缓存里取锚句所在的那一段，前后各多带几行。"""
    lines = open(os.path.join(CACHE, cache_file), encoding="utf-8",
                 errors="ignore").read().split("\n")
    idx = 0
    if anchor:
        for i, L in enumerate(lines):
            if anchor in L:
                idx = i
                break
    else:
        for i, L in enumerate(lines):
            if len(L.strip()) > 60:
                idx = i
                break
    lo, hi = max(0, idx - before), min(len(lines), idx + after + 1)
    return [L.strip() for L in lines[lo:hi] if L.strip()]


