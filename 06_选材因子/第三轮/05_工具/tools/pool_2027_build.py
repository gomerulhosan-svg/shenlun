def _plain(term):
    """含 `+` 的词必须保留标点去比，其余一律归一化去比。

    两种误差各吃过一次，才定下这条规则：
      · 全用归一化：「人工智能+」塌成「人工智能」，数出来 423 次（把全篇人工智能都算了）。
      · 全用保留标点：「首台套、首批次、首版次」要靠塌掉顿号才等于「首台套首批次首版次」，
        2025 报告用的正是带顿号的写法，于是首现被误判成 2026。
    判据：`+` 是语义的一部分（人工智能+ ≠ 人工智能）；`、` 不是。

    返回 (用于比对的词, 是否改用保留标点版)。
    注意必须用**显式布尔**决定走哪条路——不能拿 `needle == term` 判断：
    没标点的词归一化后等于自己，会被误判成「含 +」那一类。
    """
    if '+' in term:
        return term, True
    return norm(term), False


def vec(term):
    needle, keep_punct = _plain(term)
    if len(needle) < 2:
        return None
    src = QRAW if keep_punct else NORM
    return ''.join('●' if needle in src[y] else '·' for y in YEARS)


def first_year(term):
    needle, keep_punct = _plain(term)
    src = QRAW if keep_punct else NORM
    for y in YEARS:
        if needle in src[y]:
            return y
    return None


def mat_count(term):
    """材料支撑：只在 2026 大事记与六份主题报道里数。

    「报告出现数」不算在材料里——那是候选的来源，用它证明它会自我循环。
    """
    needle, keep_punct = _plain(term)
    src = MAT_Q if keep_punct else MAT_NORM
    return sum(txt.count(needle) for txt in src.values())


