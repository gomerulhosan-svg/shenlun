def read(p):
    return p.read_text(encoding='utf-8').strip()


def demote(text, levels=2):
    """把素材里的 # 标题降 levels 级，避免与合装文件的层级冲突。"""
    return '\n'.join(
        ('#' * levels + l) if l.startswith('#') else l
        for l in text.split('\n')
    )


def hanzi(s):
    return len(re.findall(r'[一-鿿]', s))


