def body(fn, start, end=None, tail_skip=0):
    """从缓存里取正文：从 start 标记起，到 end 标记止。"""
    t = open(os.path.join(CACHE, fn), encoding="utf-8").read()
    i = t.find(start)
    if i < 0:
        raise SystemExit("找不到起点 %s @ %s" % (start, fn))
    if end:
        j = t.find(end, i)
        if j < 0:
            raise SystemExit("找不到终点 %s @ %s" % (end, fn))
    else:
        j = len(t)
    lines = [L.strip() for L in t[i:j].split("\n")]
    return "\n".join([L for L in lines if L])


def quoted(text):
    return "\n".join("> " + L for L in text.split("\n"))


