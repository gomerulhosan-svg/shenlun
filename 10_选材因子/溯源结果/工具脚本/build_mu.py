        for L in lines:
            s = L.strip()
            if re.match(r"^[一二三四五六七八九十]+、20", s):
                out.append(s[:40])
            elif re.match(r"^（[一二三四五六七八九十]+）", s):
                out.append("    " + s.split("。")[0] + "。")
        return "\n".join(out)
