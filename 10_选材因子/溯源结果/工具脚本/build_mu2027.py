def cut(text, start, end, keep_end=True, name=""):
    """取 start 与 end 之间（含两端）的原文。start/end 必须唯一命中。"""
    i = text.find(start)
    if i < 0:
        raise SystemExit("ANCHOR-START MISS [%s]: %r" % (name, start[:40]))
    j = text.find(end, i)
    if j < 0:
        raise SystemExit("ANCHOR-END MISS [%s]: %r" % (name, end[:40]))
    return text[i:j + (len(end) if keep_end else 0)]


def quote(block, prefix="> "):
    """逐行加引用前缀，空行保留。"""
    return "\n".join((prefix + l if l.strip() else prefix.rstrip()) for l in block.split("\n"))


def sec(title, block):
    return quote(block)


