MAT = "材料一二三四五六七八九十"

SEC_0 = re.compile(r"(?m)^#{2,4}\s*[〇零0][、.．]")
SEC_MU = re.compile(r"(?m)^#{2,4}\s*[一二三四五六七八九十\d]*[、.．]?\s*母文件")
SEC_MAT = re.compile(r"(?m)^#{2,4}\s*材料[" + MAT + r"]〔\d+〕")
SEC_ANYMAT = re.compile(r"(?m)^#{2,4}\s*材料[" + MAT + r"]")
DEG = re.compile(r"(?m)^\s*-\s*对应程度")
ANON = re.compile(r"(?m)^\s*-\s*匿名对象识别")

# 自曝没做完的标记（跟 coverage.py 同一个口径，宁可把可疑的算成没做）
UNDONE = re.compile(r"本轮未完成|本轮未做完|未及|整则未|尚未做|下次接着做|下次从")
NOTFOUND = re.compile(r"未找到|未取到")
ONLYABS = re.compile(r"仅摘要|未打开全文")

# 交付件里「本轮未完成」出现在哪一行，把那一行的段号/材料名一起抓出来
LINE_SEG = re.compile(r"〔(\d+)〕")


def segs_covered(path):
    """交付件声明覆盖了哪些段（标题里的段号，含〔3〕～〔8〕这种区间）。

    按**行**解析：`SEC_ANYMAT` 这类 `^#{2,4}\\s*材料[一二…]` 的模式只匹配到
    「材料二」就停，后面行尾的〔3〕～〔8〕根本不在 match 里——第一版就是这么
    把「已覆盖」全算成 0 的。所以这里改成逐行取标题整行再取段号。
    """
    t = open(path, encoding="utf-8").read()
    cov = {}
    for ln in t.split("\n"):
        m = re.match(r"^#{2,4}\s*(材料[" + MAT + r"])(.*)$", ln)
        if not m:
            continue
        mat, tail = m.group(1), m.group(2)
        nums = set()
        for r in re.finditer(r"〔(\d+)〕\s*[～~—\-－]\s*〔(\d+)〕", tail):
            a, b = int(r.group(1)), int(r.group(2))
            if a <= b:
                nums.update(range(a, b + 1))
        for r in LINE_SEG.finditer(tail):
            nums.add(int(r.group(1)))
        cov.setdefault(mat, set()).update(nums)
    return cov


def src_segments(name):
    """源卷里每一则有哪几段。"""
    p = os.path.join(SRC, name + "_材料与题干.md")
    if not os.path.exists(p):
        return {}
    t = open(p, encoding="utf-8").read()
    mm = re.search(r"(?m)^#+\s*题干", t)
    body = t[:mm.start()] if mm else t
    out = {}
    marks = list(SEC_ANYMAT.finditer(body))
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(body)
        mat = m.group(0).strip("# ").split("〔")[0].strip()
        out[mat] = sorted(int(x) for x in LINE_SEG.findall(body[m.end():end]))
    return out


