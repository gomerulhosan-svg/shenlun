def read(fn):
    return open(os.path.join(CACHE, fn), encoding="utf-8").read()


def _find(t, marker, full_line=True):
    """先按整行匹配，找不到再退化为普通子串匹配。"""
    if full_line:
        i = t.find("\n" + marker + "\n")
        if i >= 0:
            return i + 1
    i = t.find(marker)
    if i < 0:
        raise SystemExit("找不到标记：%r" % marker[:60])
    return i


def body(fn, start, end=None):
    """从缓存里取正文：从 start 标记起，到 end 标记止。"""
    t = read(fn)
    i = _find(t, start)
    if end:
        j = _find(t, end)
        if j < i:
            raise SystemExit("终点在起点之前：%s @ %s" % (end[:40], fn))
    else:
        j = len(t)
    lines = [L.strip() for L in t[i:j].split("\n")]
    return "\n".join([L for L in lines if L])


def quoted(text):
    return "\n".join("> " + L for L in text.split("\n"))


def toc(fn, start, end, sub_re):
    """从报告里取各级标题：一级「一、」二级「（一）」，可选三级。"""
    t = read(fn)
    i = _find(t, start)
    j = _find(t, end)
    out = []
    for L in t[i:j].split("\n"):
        s = L.strip()
        if re.match(r"^[一二三四五六七八九十]+、", s):
            out.append(s)
        elif re.match(r"^（[一二三四五六七八九十]+）", s):
            out.append("    " + s)
        elif sub_re and re.match(sub_re, s):
            out.append("        " + s)
    return "\n".join(out)


def toc_plan(fn, start, end):
    """规划建议的目录：「一、」+「(1)」，条目只取标题句，不含正文。"""
    t = read(fn)
    i = _find(t, start)
    j = _find(t, end)
    out = []
    for L in t[i:j].split("\n"):
        s = L.strip()
        if re.match(r"^[一二三四五六七八九十]+、", s):
            out.append(s)
        elif re.match(r"^\(\d+\)", s):
            # 「(1)“十四五”时期广东取得的发展成就。……」—— 只留到第一个句号
            head = re.match(r"^(\(\d+\)[^。]*。)", s)
            out.append("    " + (head.group(1) if head else s[:60]))
    return "\n".join(out)


def titles(fn, start, end):
    """只取各级标题行（一、/（一）/1．/专栏）."""
    t = read(fn)
    i = _find(t, start)
    j = _find(t, end)
    out = []
    for L in t[i:j].split("\n"):
        s = L.strip()
        if re.match(r"^[一二三四五六七八九十]+、", s):
            out.append(s)
    return "\n".join(out)


