def span(fn, start_anchor, end_anchor):
    ls = lines_of(fn)
    i = next(i for i, L in enumerate(ls) if start_anchor in L)
    j = next(j for j, L in enumerate(ls) if end_anchor in L)
    return [L for L in ls[i:j + 1] if L]


