def lines_of(fn):
    return [L.strip() for L in
            open(os.path.join(CACHE, fn), encoding="utf-8", errors="ignore").read().split("\n")]


def para(fn, anchor, before=1, after=1):
    """取锚句所在那一整段（缓存里一段=一行），前后各多带 before/after 段。"""
    ls = lines_of(fn)
    hit = [i for i, L in enumerate(ls) if anchor in L]
    if not hit:
        raise SystemExit("锚句找不到：%s / %s" % (fn, anchor))
    i = hit[0]
    return [L for L in ls[max(0, i - before): i + after + 1] if L]


def quote(ls):
    return ["  > " + L for L in ls]


def block(num, degree, sources, anon, note=None):
    """sources = [(来源行, 原文行列表), ...]"""
    out = ["### 材料五〔%s〕" % num, "- 对应程度：%s" % degree]
    for i, (s, q) in enumerate(sources, 1):
        out.append("- 来源%d：%s" % (i, s))
        out.append("  - 原文（逐字粘贴，和这段材料对应的那一整段；前后各多贴一段）：")
        out += quote(q)
    if note:
        out.append("- 备注：%s" % note)
    out.append("- 匿名对象识别：%s" % anon)
    return out


