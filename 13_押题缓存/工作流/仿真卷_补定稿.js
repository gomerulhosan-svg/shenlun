phase('Verify')
const CHECKS = [
  { key: '一致性', prompt: `只看最终文件 ${DIR}/试卷.md、${DIR}/参考答案与解析.md、${DIR}/命题说明.md。逐条核对：
- 参考答案每一条、逐句解析里每一处引的材料原句和段号，在试卷.md 的材料里逐字找得到（写脚本核）；
- 问题一答案的每个要点确实是材料三里的正面做法或表现，没有材料外的内容；问题二的每个问题在材料五里有人说过，每条对策有材料依据或能从问题反推；
- 三道题字数在限内；题干、要求语和出卷规范第三节一致；
- 命题说明里的自检表数值和你用脚本重算的一致。` },
  { key: '规范与真实性', prompt: `对照 11_仿真卷/出卷规范.md 和真卷，核查 ${DIR}/ 下的最终文件：
- 作文材料里每个数字、每句讲话原话，能在规定的真实材料里 grep 到（重跑 _过程/ 下两个核对脚本，再自己抽 15 处独立核）；
- 小题材料里真实地名为 0，真实企业名、人名为 0；合成内容在命题说明里逐条标了"合成/示意"；
- 材料三读起来像不像真卷问题一材料（对照 2025、2026 省市卷问题一材料），还有没有模板化的小标题或排比；材料五是否写明组织方、身份与题干对应、对策执行主体与身份层级一致；
- 没有任何高分考生卷原文（与 07_句子层、08_小题重写 里的考生答案对照）；
- 首段是否背景，干扰内容是否合理。` },
]
const verdicts = (await parallel(CHECKS.map(c => () => agent(`${CONTEXT}
【你的任务：独立核查（${c.key}）】你没参与出卷，也看不到另一位核查员的结果。
${c.prompt}
把发现的问题写到 ${DIR}/_过程/定稿核查_${c.key}.md：每条写位置、问题、证据、严重程度（高/中/低）、建议怎么改。没有问题也要写明核了哪些、怎么核的。
返回：高、中、低各几条，以及最严重的 3 条。`, { label: 'verify:' + c.key, phase: 'Verify' }).then(text => ({ key: c.key, text }))))).filter(Boolean)

phase('Repair')
const repair = await agent(`${CONTEXT}
【你的任务：按定稿核查修正】读 ${DIR}/_过程/定稿核查_一致性.md 和 ${DIR}/_过程/定稿核查_规范与真实性.md。
高、中两级的问题全部处理：能改的改（改了材料要同步答案、解析和命题说明），不改的写理由；低级的顺手能改就改。处理结果追加到 ${DIR}/_过程/审查意见处理记录.md 末尾，另起一节"定稿核查"。
改完重跑：两个核对脚本；答案引文和段号核对；字数统计；命题说明自检表数值。全部通过才算完。
返回：处理了几条、没处理的几条及理由、最终的全卷字数和三道题字数、各项核对结果。`, { label: 'repair', phase: 'Repair' })

return { fix, assemble, verdicts, repair }
